/*
 * tws_lp_jis60 トラックボール (PMW3610) 設定ファイル
 *
 * カーソルの感度と向きの調整はこのファイルだけで完結する。
 * このファームウェアはカーソル移動だけを送る。クリックやスクロールは扱わず、キーマップも変更しない。
 * 値を変えたら `./build.sh right` で右手側を再ビルドして書き込む (左手側は再書き込み不要)。
 */
#ifndef TWS_LP_JIS60_TRACKBALL_CONFIG_H
#define TWS_LP_JIS60_TRACKBALL_CONFIG_H

/* ---- 配線 (センサー基板の信号を XIAO のどの D ピンにつないだか) ------------------ */
/* 8 / 9 / 10 のいずれかを重複なく指定する (D8=P1.13, D9=P1.14, D10=P1.15)。
 * はんだをやり直さなくても、ここを実際の配線に合わせれば動く。
 */
#define TB_PIN_SDIO 8  /* センサー SDIO → XIAO D8  */
#define TB_PIN_SCLK 9  /* センサー SCLK → XIAO D9  */
#define TB_PIN_NCS  10 /* センサー nCS  → XIAO D10 */
/* MOTION をつないだ裏面パッド。1 = NFC1 (P0.09), 2 = NFC2 (P0.10) */
#define TB_PIN_MOTION_NFC 1

/* ---- カーソル感度 ------------------------------------------------------------ */
/* センサー解像度。200〜3200 を 200 刻みで指定。大きいほど速い。まずここを変える。 */
#define TB_CPI 600

/* CPI で合わせきれない時の微調整。移動量に MUL/DIV を掛ける (端数は持ち越される)。
 * 例: 3/2 で 1.5 倍、1/2 で半分。 */
#define TB_SCALE_MUL 1
#define TB_SCALE_DIV 1

/* ---- カーソルの向き (実機で動かして決める) -------------------------------------- */
/* 0 = 無効, 1 = 有効。処理の順序は「まず軸を入れ替え、そのあと画面上の向きを反転」。
 * 手順: (1) ボールを右へ回して上下に動くなら TB_SWAP_XY を 1 にする
 *       (2) そのうえで画面上の左右が逆なら TB_INVERT_X、上下が逆なら TB_INVERT_Y を 1 にする */
#define TB_SWAP_XY  1 /* センサーが 90 度回って付いているので入れ替える */
#define TB_INVERT_X 1 /* 画面上の左右を反転 */
#define TB_INVERT_Y 1 /* 画面上の上下を反転 */

/* ---- 応答性と電池 --------------------------------------------------------------- */
/* 1 にするとキーボードがアクティブな間センサーを常時起こしておく。
 * 動き出しの引っかかりが減るが電池消費が増える。 */
#define TB_FORCE_AWAKE 0

/* SPI クロック (Hz)。配線が長い (~30cm) ので控えめ。不安定ならさらに下げる (例 500000)。 */
#define TB_SPI_FREQ 1000000

#endif /* TWS_LP_JIS60_TRACKBALL_CONFIG_H */
